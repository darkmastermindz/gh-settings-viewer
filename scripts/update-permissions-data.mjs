#!/usr/bin/env node
// Refreshes data/github-app-permissions.json and src/core/registry/manifest-permissions.ts
// from GitHub's own docs source (github/docs), the data behind
// https://docs.github.com/en/rest/authentication/permissions-required-for-github-apps
//
// Usage: npm run update:permissions-data [-- --from <path to a github/docs checkout>]
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const VERSION = 'ghec-2022-11-28'; // GitHub.com + Enterprise Cloud (includes enterprise permissions)
const root = resolve(import.meta.dirname, '..');
const fromIdx = process.argv.indexOf('--from');
let docsDir = fromIdx > -1 ? resolve(process.argv[fromIdx + 1]) : null;
let cleanup = null;

if (!docsDir) {
  docsDir = mkdtempSync(join(tmpdir(), 'ghdocs-'));
  cleanup = docsDir;
  const git = (...args) => execFileSync('git', args, { cwd: docsDir, stdio: 'inherit' });
  git('clone', '--depth', '1', '--filter=blob:none', '--sparse', 'https://github.com/github/docs.git', '.');
  git('sparse-checkout', 'set', '--no-cone', `/src/github-apps/data/${VERSION}/`);
}

try {
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: docsDir }).toString().trim();
  const raw = JSON.parse(readFileSync(join(docsDir, 'src/github-apps/data', VERSION, 'server-to-server-permissions.json'), 'utf8'));

  const categoryOf = (displayTitle) => {
    if (displayTitle.startsWith('Enterprise')) return 'enterprise';
    if (displayTitle.startsWith('Organization')) return 'organization';
    if (displayTitle.startsWith('Repository')) return 'repository';
    if (displayTitle.startsWith('User')) return 'account';
    throw new Error(`Unknown permission category: ${displayTitle}`);
  };

  const permissions = {};
  for (const [name, value] of Object.entries(raw)) {
    const levels = new Set();
    const get = [];
    for (const p of value.permissions) {
      levels.add(p.access);
      if (p.verb === 'get' && p['server-to-server']) {
        get.push({ path: p.requestPath, access: p.access, additional: Boolean(p['additional-permissions']) });
      }
    }
    permissions[name] = {
      title: value.title,
      category: categoryOf(value.displayTitle),
      accessLevels: [...levels].sort(),
      get: get.sort((a, b) => a.path.localeCompare(b.path)),
    };
  }

  const out = {
    source: { repository: 'github/docs', commit, version: VERSION, file: `src/github-apps/data/${VERSION}/server-to-server-permissions.json` },
    permissions,
  };
  writeFileSync(join(root, 'data/github-app-permissions.json'), JSON.stringify(out, null, 2) + '\n');

  // Read-only permission keys the manifest flow can request. The manifest can't set enterprise
  // permissions, and write-only permissions are left out (this tool never asks for write).
  const manifest = Object.entries(permissions)
    .filter(([, p]) => p.category !== 'enterprise' && p.accessLevels.includes('read'))
    .map(([name, p]) => ({ name, title: p.title, category: p.category }));
  const enterprise = Object.entries(permissions)
    .filter(([, p]) => p.category === 'enterprise' && p.accessLevels.includes('read'))
    .map(([name, p]) => ({ name, title: p.title, category: p.category }));
  const ts = `// Generated by scripts/update-permissions-data.mjs from github/docs@${commit.slice(0, 12)} (${VERSION}). Do not edit.
export interface PermissionInfo { name: string; title: string; category: 'organization' | 'repository' | 'account' | 'enterprise' }

/** Read-capable organization, repository and account permissions: what the manifest flow requests. */
export const MANIFEST_READ_PERMISSIONS: readonly PermissionInfo[] = ${JSON.stringify(manifest, null, 2)};

/** Read-capable enterprise permissions. Manifests can't request these, so setup prints them as manual steps. */
export const ENTERPRISE_READ_PERMISSIONS: readonly PermissionInfo[] = ${JSON.stringify(enterprise, null, 2)};
`;
  writeFileSync(join(root, 'src/core/registry/manifest-permissions.ts'), ts);
  console.log(`Wrote ${Object.keys(permissions).length} permissions from github/docs@${commit.slice(0, 12)}`);
} finally {
  if (cleanup) rmSync(cleanup, { recursive: true, force: true });
}
